    /// Creates or replaces a notification for a group. All direct & descendant members see it.
    #[oai(path = "/groups/:group_id/push_notifications/:id", method = "put")]
    async fn put_group_notification(
        &self,
        user: User,
        Path(group_id): Path<Uuid>,
        Path(id): Path<Uuid>,
        Json(body): Json<PutNotification>,
    ) -> MinilithResult<Json<GroupNotification>> {
        check_direct_adminship(&self.db, user.get_id(), group_id).await?;
        let mut txn = self.db.begin().await?;
        let sender = sqlx::query_scalar!(
            r#"select name as "name!: DIS" from groups where id = $1 for update"#,
            group_id,
        )
        .fetch_one(&mut txn.executor())
        .await?;
        let existing = sqlx::query!(
            r#"select news_push_notifications.notification_id, push_notifications.sent
            from news_push_notifications
            inner join push_notifications on push_notifications.id = news_push_notifications.notification_id
            inner join news on news.id = news_push_notifications.news_id
            where news_push_notifications.id = $1 and news.target_group_id = $2
            for update of push_notifications"#,
            id,
            group_id
        )
        .fetch_optional(&mut txn.executor())
        .await?;
        if existing
            .as_ref()
            .is_some_and(|notification| notification.sent)
        {
            return Err(MinilithEndpointError::bad_frontend_code(
                "cannot edit a sent notification",
                "create a new notification instead",
            ));
        }
        let notification_id =
            existing.map_or_else(Uuid::new_v4, |notification| notification.notification_id);
        sqlx::query!(
            r#"insert into push_notifications (id, kind, sender, title, content, send_at)
            values ($1, 'news', $2, $3, $4, $5)
            on conflict (id) do update set
                kind = excluded.kind,
                sender = excluded.sender,
                title = excluded.title,
                content = excluded.content,
                send_at = excluded.send_at
            where push_notifications.sent = false"#,
            notification_id,
            sender.to_json_value(),
            body.title.to_json_value(),
            body.content.to_json_value(),
            body.send_at,
        )
        .execute(&mut txn.executor())
        .await?;
        sqlx::query!(
            r#"insert into news (id, target_group_id, title, content, published_at)
            values ($1, $2, $3, $4, $5)
            on conflict (id) do update set
                target_group_id = excluded.target_group_id,
                title = excluded.title,
                content = excluded.content,
                published_at = excluded.published_at"#,
            id,
            group_id,
            body.title.to_json_value(),
            body.content.to_json_value(),
            body.send_at,
        )
        .execute(&mut txn.executor())
        .await?;
        let affected = sqlx::query!(
            r#"insert into news_push_notifications
                (id, news_id, notification_id)
            values ($1, $1, $2)
            on conflict (id) do update set
                notification_id = excluded.notification_id
            where news_push_notifications.news_id = excluded.news_id"#,
            id,
            notification_id,
        )
        .execute(&mut txn.executor())
        .await?;
        if affected.rows_affected() != 1 {
            return Err(MinilithEndpointError::bad_frontend_code(
                "not unique notification id",
                "",
            ));
        }
        txn.commit().await?;
        Ok(Json(GroupNotification {
            id,
            sender: sender.0,
            sent: false,
            n_sent: 0,
            n_opened: 0,
            n_dismissed: 0,
            notification: body,
        }))
    }

