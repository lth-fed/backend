    /// Adds what was purchased (minus supplier returns) to the sellable stock of every product in
    /// the movement whose stock is managed automatically and is not unlimited.
    ///
    /// # Errors
    ///
    /// AUTH, DB, NOT FOUND.
    #[oai(
        path = "/stock-transactions/:id/replenish-sales-stock",
        method = "post"
    )]
    async fn replenish_sales_stock(
        &self,
        user: User,
        Path(id): Path<Uuid>,
    ) -> MinilithResult<Json<u32>> {
        let group_id =
            sqlx::query_scalar!("select group_id from stock_transactions where id = $1", id)
                .fetch_optional(&self.db)
                .await?
                .wrap_err_not_found()?;
        check_direct_adminship(&self.db, user.get_id(), group_id).await?;
        // A supplier return and a purchase of the same amount cancel out; the sellable stock only
        // grows with what is actually left in the store.
        let affected = sqlx::query(
            "update products
            set sales_stock = least(2147483647, products.sales_stock + delta.total)::int
            from (
                select record.product_id,
                    sum(case
                        when record.kind = 'purchase' then record.amount
                        when record.kind = 'refund' then -record.amount
                        else 0
                    end) as total
                from stock_transaction_records record
                where record.transaction_id = $1
                group by record.product_id
            ) delta
            where products.id = delta.product_id
            and products.sales_stock is not null
            and products.sales_stock < 1000000000
            and delta.total > 0",
        )
        .bind(id)
        .execute(&self.db)
        .await?;
        Ok(Json(
            u32::try_from(affected.rows_affected()).unwrap_or(u32::MAX),
        ))
    }

