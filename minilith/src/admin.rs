async fn sync_ticket_pre_release_notification(
    txn: &mut bin_common::Transaction<'_>,
    activity_id: Uuid,
    create_if_missing: bool,
) -> MinilithResult<()> {
    let release = sqlx::query!(
        r#"select
            activities.title as "sender!: DIS",
            min(products.sales_start) as "released_at?"
        from activities
        left join product_activity_assignments assignment on assignment.activity_id = activities.id
        left join products
            on products.id = assignment.product_id
            and products.kind = 'ticket'
            and products.sales_start > now()
        where activities.id = $1
        group by activities.id, activities.title"#,
        activity_id,
    )
    .fetch_one(&mut txn.executor())
    .await?;
    let Some(released_at) = release.released_at else {
        return Ok(());
    };
    let send_at: OffsetDateTime = released_at - time::Duration::MINUTE * 14;

    let existing = sqlx::query_scalar!(
        r#"select notification_id from purchased_ticket_push_notifications
        where activity_id = $1 and id = $2"#,
        activity_id,
        Uuid::nil(),
    )
    .fetch_optional(&mut txn.executor())
    .await?;
    if let Some(notification_id) = existing {
        if released_at < OffsetDateTime::now_utc() + time::Duration::hours(2) {
            // A changed release must satisfy the same notice period as a new one.
            // Unrelated edits near an unchanged release keep its existing reminder.
            sqlx::query!(
                "delete from push_notifications where id = $1 and sent = false and send_at != $2",
                notification_id,
                send_at,
            )
            .execute(&mut txn.executor())
            .await?;
            return Ok(());
        }
        sqlx::query!(
            r#"update push_notifications set send_at = $2
            where id = $1 and sent = false"#,
            notification_id,
            send_at,
        )
        .execute(&mut txn.executor())
        .await?;
    } else if create_if_missing
        && released_at >= OffsetDateTime::now_utc() + time::Duration::hours(2)
    {
        let notification_id = Uuid::new_v4();
        sqlx::query!(
            r#"insert into push_notifications (id, kind, sender, title, content, send_at)
            values ($1, 'ticket_release', $2, $3, $4, $5)"#,
            notification_id,
            release.sender.to_json_value(),
            serde_json::json!({
                "sv": "biljetterna släpps snart!",
                "en": "tickets are released soon!",
            }),
            serde_json::json!({
                "sv": "Gå in i appen och ställ dig i kö för att få plats.",
                "en": "The queues are open.",
            }),
            send_at,
        )
        .execute(&mut txn.executor())
        .await?;
        insert_activity_notification_link(
            txn,
            activity_id,
            Uuid::nil(),
            notification_id,
            ActivityNotificationKind::Buyers,
        )
        .await?;
    }
    Ok(())
}

