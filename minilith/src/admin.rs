    /// Deletes an add-on only when it is not assigned to any product.
    #[oai(path = "/addons/:addon_id", method = "delete")]
    async fn delete_addon(&self, user: User, Path(addon_id): Path<Uuid>) -> MinilithResult<()> {
        let set = sqlx::query!(
            r#"select sets.id as set_id, sets.activity_id, sets.product_id
            from product_addons addons
            inner join product_addon_sets sets on sets.id = addons.set_id
            where addons.id = $1"#,
            addon_id
        )
        .fetch_optional(&self.db)
        .await?
        .ok_or_else(|| MinilithEndpointError::bad_frontend_code("addon not found", ""))?;
        let owner = match (set.activity_id, set.product_id) {
            (Some(activity_id), _) => AddonOwner::Activity(activity_id),
            (None, Some(product_id)) => AddonOwner::Product(product_id),
            (None, None) => {
                return Err(MinilithEndpointError::bad_frontend_code(
                    "addon set has no owner",
                    "",
                ));
            }
        };
        check_addon_adminship(&self.db, user.get_id(), owner).await?;
        let mut txn = self.db.begin().await?;
        if let AddonOwner::Activity(activity_id) = owner {
            lock_activity(&mut txn, activity_id).await?;
        }
        let editable = sqlx::query_scalar!(
            r#"select exists (
            select 1 from product_addons where id = $1 and set_id = $2
            and not exists (select 1 from product_addon_links links where links.addon_id = $1)
        ) as "editable!""#,
            addon_id,
            set.set_id
        )
        .fetch_one(&mut txn.executor())
        .await?;
        if !editable {
            return Err(MinilithEndpointError::bad_frontend_code(
                "addon missing or assigned to a product",
                "unassign it from every product before deleting",
            ));
        }
        sqlx::query!(
            "delete from product_addon_options where product_addon_id = $1",
            addon_id
        )
        .execute(&mut txn.executor())
        .await?;
        sqlx::query!("delete from product_addons where id = $1", addon_id)
            .execute(&mut txn.executor())
            .await?;
        txn.commit().await?;
        Ok(())
    }

    /// Creates or fully replaces an activity. A new activity must name a group
    /// directly administered by the caller as its creator and initially has no
    /// additional hosts. The creator is immutable. An existing additional host
    /// may only be removed by one of that exact group's direct admins; hosts can
    /// only be added through the invitation endpoints.
    ///
    /// The responsible name must not be blank, the contact must be a `mailto:`
    /// or `tel:` URI, the end must follow the start, and the overall ticket cap
    /// cannot be below existing reservations or purchases. `image_id` must
    /// refer to an image uploaded through `/admin/upload-image`.
    #[oai(path = "/activities/:id", method = "put")]
    #[allow(
        clippy::too_many_lines,
        reason = "there's just a lot of shit to do and it's very isolated"
    )]
    async fn put_activity(
        &self,
        user: User,
        Path(id): Path<Uuid>,
        Json(body): Json<PutActivity>,
    ) -> MinilithResult<()> {
        if body.responsible_name.trim().is_empty() {
            return Err(MinilithEndpointError::bad_frontend_code(
                "responsible_name must not be empty",
                "",
            ));
        }
        if !(body.responsible_contact.starts_with("mailto:")
            || body.responsible_contact.starts_with("tel:"))
        {
            return Err(MinilithEndpointError::bad_frontend_code(
                "responsible_contact must start with `mailto:` or `tel:`",
                "",
            ));
        }
        if body.time_end <= body.time_start {
            return Err(MinilithEndpointError::bad_frontend_code(
                "time_end must be after time_start",
                "",
            ));
        }
        if let Some(stock_group_id) = body.stock_group_id {
            check_direct_or_parent_adminship(&self.db, user.get_id(), stock_group_id).await?;
        }

        let mut txn = self.db.begin().await?;
        let existing_creator = sqlx::query_scalar!(
            "select target.group_id
            from activities
            inner join sales_targets target on target.id = activities.sales_target_id
            where activities.id = $1
            for update of activities",
            id,
        )
        .fetch_optional(&mut txn.executor())
        .await?;
        if let Some(previous_creator) = existing_creator
            && previous_creator != body.sales_target_group_id
        {
            check_direct_adminship(
                &mut txn.executor(),
                user.get_id(),
                body.sales_target_group_id,
            )
            .await?;
        }
        let mut requested_host_ids = body.host_ids.clone();
        requested_host_ids.push(body.sales_target_group_id);
        requested_host_ids.sort_unstable();
        requested_host_ids.dedup();

        let (is_new, removed_host_ids) = if existing_creator.is_some() {
            lock_activity_adminship(&mut txn, user.get_id(), id).await?;
            let current_host_ids = sqlx::query_scalar!(
                "select group_id from activity_hosts where activity_id = $1",
                id,
            )
            .fetch_all(&mut txn.executor())
            .await?;
            let administered_group_ids = sqlx::query_scalar!(
                r#"select group_id from group_adminships where user_id = $1
                for key share"#,
                user.get_id(),
            )
            .fetch_all(&mut txn.executor())
            .await?;
            (
                false,
                removed_activity_hosts(
                    body.sales_target_group_id,
                    &current_host_ids,
                    &requested_host_ids,
                    &administered_group_ids,
                )?,
            )
        } else {
            lock_direct_adminship(&mut txn, user.get_id(), body.sales_target_group_id).await?;
            removed_activity_hosts(
                body.sales_target_group_id,
                &[body.sales_target_group_id],
                &requested_host_ids,
                &[body.sales_target_group_id],
            )?;
            (true, Vec::new())
        };

        let sales_target_id = sqlx::query_scalar!(
            "select id from sales_targets where group_id = $1 order by id limit 1",
            body.sales_target_group_id,
        )
        .fetch_optional(&mut txn.executor())
        .await?
        .wrap_err_bad_frontend("the creator group has no sales target")?;
        self.ensure_image_registered(&mut txn, body.image_id)
            .await?;

        let existing_base_ticket =
            sqlx::query_scalar!("select base_ticket from activities where id = $1", id,)
                .fetch_optional(&mut txn.executor())
                .await?;
        let base_ticket = match existing_base_ticket {
            Some(base_ticket) => base_ticket,
            None => {
                create_activity_visibility_product(
                    &mut txn,
                    sales_target_id,
                    &body.title,
                    &body.description,
                    body.time_start,
                    body.time_end,
                )
                .await?
            }
        };

        let name = body
            .location
            .name
            .as_ref()
            .map(InternationalizedString::to_json_value);
        let directions = body
            .location
            .directions
            .as_ref()
            .map(InternationalizedString::to_json_value);
        let (north, east) = body
            .location
            .coordinate_wgs84
            .map_or((None, None), |point| (Some(point.north), Some(point.east)));

        let saved = sqlx::query!(
            r#"insert into activities (
                id, responsible_name, responsible_contact, sales_target_id,
                title, description, location, time_start, time_end, image_id,
                is_hidden, is_hidden_for_other_admins, max_tickets_per_user, base_ticket,
                stock_group
            )
            values (
                $1, $2, $3, $4, $5, $6,
                row(
                    $7::jsonb,
                    $8::jsonb,
                    case when $9::float8 is null or $10::float8 is null
                        then null else point($9, $10) end,
                    $11
                )::location,
                $12, $13, $14, $15, $16, $17, $18, $19
            )
            on conflict (id) do update set
                responsible_name = excluded.responsible_name,
                responsible_contact = excluded.responsible_contact,
                title = excluded.title,
                description = excluded.description,
                location = excluded.location,
                time_start = excluded.time_start,
                time_end = excluded.time_end,
                image_id = excluded.image_id,
                is_hidden = excluded.is_hidden,
                is_hidden_for_other_admins = excluded.is_hidden_for_other_admins,
                max_tickets_per_user = excluded.max_tickets_per_user,
                stock_group = excluded.stock_group"#,
            id,
            body.responsible_name,
            body.responsible_contact,
            sales_target_id,
            body.title.to_json_value(),
            body.description.to_json_value(),
            name,
            directions,
            north,
            east,
            body.location.url,
            body.time_start,
            body.time_end,
            body.image_id,
            body.is_hidden,
            body.is_hidden_for_other_admins,
            body.max_tickets_per_user,
            base_ticket,
            body.stock_group_id,
        )
        .execute(&mut txn.executor())
        .await?;
        if saved.rows_affected() != 1 {
            return Err(MinilithEndpointError::bad_frontend_code(
                "the activity was concurrently created with another creator",
                "",
            ));
        }
        if is_new {
            sqlx::query!(
                "insert into activity_hosts (activity_id, group_id) values ($1, $2)",
                id,
                body.sales_target_group_id,
            )
            .execute(&mut txn.executor())
            .await?;
            link_activity_visibility_product(&mut txn, id, base_ticket).await?;
        } else if !removed_host_ids.is_empty() {
            sqlx::query!(
                "delete from activity_hosts where activity_id = $1 and group_id = any($2)",
                id,
                &removed_host_ids,
            )
            .execute(&mut txn.executor())
            .await?;
        }
        sqlx::query!(
            r#"update push_notifications set sender = $2
            where id in (
                select notification_id from activity_push_notifications where activity_id = $1
                union
                select notification_id from purchased_ticket_push_notifications where activity_id = $1
                union
                select notification_id from purchased_ticket_push_notifications where activity_id = $1
            )"#,
            id,
            body.title.to_json_value(),
        )
        .execute(&mut txn.executor())
        .await?;
        txn.commit().await?;

        Ok(())
    }

    /// Permanently deletes an unpublished activity with no ticket kinds.
    ///
    /// The activity row is locked while checking the contract, preventing a
    /// ticket kind from being created concurrently with deletion.
    #[oai(path = "/activities/:id", method = "delete")]
    async fn delete_activity(&self, user: User, Path(id): Path<Uuid>) -> MinilithResult<()> {
        check_activity_adminship(&self.db, user.get_id(), id).await?;
        let mut txn = self.db.begin().await?;
        let activity = sqlx::query!(
            r#"select
                is_hidden,
                exists (select 1 from product_activity_assignments where activity_id = $1) as "has_ticket_kinds!",
                exists (
                    select 1
                    from push_notifications
                    where id in (
                        select notification_id from activity_push_notifications where activity_id = $1
                        union
                        select notification_id from purchased_ticket_push_notifications where activity_id = $1
                        union
                        select notification_id from purchased_ticket_push_notifications where activity_id = $1
                    )
                ) as "has_sent_notifications!"
            from activities
            where id = $1
            for update"#,
            id,
        )
        .fetch_optional(&mut txn.executor())
        .await?
        .wrap_err_not_found()?;

        if !activity.is_hidden {
            return Err(MinilithEndpointError::bad_frontend_code(
                "cannot delete a published activity",
                "hide the activity before deleting it",
            ));
        }
        if activity.has_ticket_kinds {
            return Err(MinilithEndpointError::bad_frontend_code(
                "cannot delete an activity with ticket kinds",
                "delete every ticket kind first",
            ));
        }
        if activity.has_sent_notifications {
            return Err(MinilithEndpointError::bad_frontend_code(
                "cannot delete an activity with sent push_notifications",
                "sent push_notifications are retained as notification history",
            ));
        }

        sqlx::query!("delete from product_addon_sets where activity_id = $1", id)
            .execute(&mut txn.executor())
            .await?;
        sqlx::query!("delete from activities where id = $1", id)
            .execute(&mut txn.executor())
            .await?;
        txn.commit().await?;
        Ok(())
    }

