/// Every activity needs a product that encodes who may see it. It is never sold; admins may later
/// turn it into a normal ticket.
///
/// The product itself can be created before the activity exists, but the
/// `product_activity_assignments` row cannot: link it with
/// [`link_activity_visibility_product`] once the activity row is inserted.
async fn create_activity_visibility_product(
    txn: &mut bin_common::Transaction<'_>,
    sales_target_id: Uuid,
    title: &InternationalizedString,
    description: &InternationalizedString,
    time_start: OffsetDateTime,
    time_end: OffsetDateTime,
) -> MinilithResult<Uuid> {
    sqlx::query!(
        r#"insert into product_tags (id, group_id, hidden, name)
        select uuidv4(), target.group_id, false, '{"en":"Ticket"}'::jsonb
        from sales_targets target
        where target.id = $1
        and not exists (
            select 1 from product_tags tag where tag.group_id = target.group_id
        )"#,
        sales_target_id,
    )
    .execute(&mut txn.executor())
    .await?;

    let product_id = Uuid::new_v4();
    sqlx::query!(
        r#"insert into products (
            id, group_id, kind, name, description, sales_organization,
            sales_stock, stock_real, stock_unit, stock_price, max_uses,
            sales_start, sales_stop, resale_start, resale_stop
        )
        select
            $1, target.group_id, 'activity_visibility', $3, $4, target.id,
            0, 0, 'st', 0, 1, $5, $6, $6, $6
        from sales_targets target
        where target.id = $2"#,
        product_id,
        sales_target_id,
        title.to_json_value(),
        description.to_json_value(),
        time_start,
        time_end,
    )
    .execute(&mut txn.executor())
    .await?;
    // Free, so the base price books nothing.
    crate::admin_addons::save_base_price_addon(txn, product_id, title, 0, &[], &[]).await?;
    Ok(product_id)
}

