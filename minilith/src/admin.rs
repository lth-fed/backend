/// Requires direct adminship of every group, and at least one group.
async fn ensure_groups_are_administered(
    db: &crate::PgPool,
    admin_id: &str,
    group_ids: &[Uuid],
) -> MinilithResult<()> {
    if group_ids.is_empty() {
        return Err(MinilithEndpointError::bad_user_input(
            "group_ids is empty",
            "",
            "select at least one group",
            "group_ids",
        ));
    }
    for group_id in group_ids {
        check_direct_adminship(db, admin_id, *group_id).await?;
    }
    Ok(())
}

/// Inserts the user and their group memberships. Returns `false` (and writes nothing) if the user
/// already exists.
async fn insert_user_with_memberships(
    txn: &mut bin_common::Transaction<'_>,
    user_id: &str,
    name: &[u8],
    language: &[u8],
    specific: bool,
    group_ids: &[Uuid],
    // When the memberships expire; `None` means they never do.
    until: Option<OffsetDateTime>,
) -> MinilithResult<bool> {
    let inserted = sqlx::query_scalar!(
        "insert into users (id, name, language) values ($1, $2, $3)
        on conflict (id) do nothing
        returning id",
        user_id,
        name,
        language,
    )
    .fetch_optional(&mut txn.executor())
    .await?;
    if inserted.is_none() {
        return Ok(false);
    }
    sqlx::query!(
        "insert into group_memberships (user_id, group_id, specific, until)
        select $1, group_id, $3, $4 from unnest($2::uuid[]) as group_id
        on conflict (user_id, group_id) do update set specific = excluded.specific",
        user_id,
        group_ids,
        specific,
        until,
    )
    .execute(&mut txn.executor())
    .await?;
    Ok(true)
}

