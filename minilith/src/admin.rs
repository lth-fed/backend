/// A non-base ticket kind may only be sold to people who can buy the activity's base ticket:
/// each of its allowed groups must be the base ticket's group or below one of its groups.
/// The base ticket itself is exempt, and so are products that are not linked to an activity.
#[allow(
    clippy::allow_attributes_without_reason,
    reason = "generated by the sqlx::query_scalar! expansion for the array parameter"
)]
async fn ensure_extra_ticket_within_base(
    db: impl PgExecutor<'_>,
    product_id: Uuid,
    activity_ids: &[Uuid],
    allowed_group_ids: &[Uuid],
) -> MinilithResult<()> {
    let outside = sqlx::query_scalar!(
        r#"select exists (
            select 1
            from unnest($2::uuid[]) allowed(group_id)
            inner join groups allowed_group on allowed_group.id = allowed.group_id
            cross join unnest($3::uuid[]) activity_id
            inner join activities activity on activity.id = activity_id
            where activity.base_ticket <> $1
            and not exists (
                select 1
                from product_allowed_groups base_allowed
                inner join groups base_group on base_group.id = base_allowed.group_id
                where base_allowed.product_id = activity.base_ticket
                and base_group.path @> allowed_group.path
            )
        ) as "outside!""#,
        product_id,
        allowed_group_ids,
        activity_ids,
    )
    .fetch_one(db)
    .await?;
    if outside {
        return Err(MinilithEndpointError::bad_frontend_code(
            "extra ticket kinds may only be sold to buyers of the base ticket",
            "allowed_group_ids",
        ));
    }
    Ok(())
}

