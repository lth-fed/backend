/// Admins may manage a product if they directly administer its owning group or a host of one
/// of its activities.
async fn check_product_adminship(
    db: impl PgExecutor<'_>,
    user_id: &str,
    product_id: Uuid,
) -> MinilithResult<()> {
    let allowed = sqlx::query_scalar!(
        r#"select exists (
            select 1
            from products
            inner join group_adminships on group_adminships.group_id = products.group_id
            where products.id = $2 and group_adminships.user_id = $1
        ) or exists (
            select 1
            from products
            inner join product_activity_assignments assignment
                on assignment.product_id = products.id
            inner join activity_hosts on activity_hosts.activity_id = assignment.activity_id
            inner join group_adminships on group_adminships.group_id = activity_hosts.group_id
            where products.id = $2 and group_adminships.user_id = $1
        ) as "exists!""#,
        user_id,
        product_id,
    )
    .fetch_one(db)
    .await?;
    if allowed {
        Ok(())
    } else {
        Err(MinilithEndpointError::bad_frontend_code(
            "must directly administer the product's group or an activity host",
            "",
        ))
    }
}

/// Addon sets belong to an activity or to a product; the owner's id doubles as the set id.
#[derive(Clone, Copy, Debug)]
enum AddonOwner {
    Activity(Uuid),
    Product(Uuid),
}

impl AddonOwner {
    /// Resolves the owner from an endpoint's query parameters (exactly one of them).
    fn from_query(activity_id: Option<Uuid>, product_id: Option<Uuid>) -> MinilithResult<Self> {
        match (activity_id, product_id) {
            (Some(activity_id), None) => Ok(Self::Activity(activity_id)),
            (None, Some(product_id)) => Ok(Self::Product(product_id)),
            _ => Err(MinilithEndpointError::bad_frontend_code(
                "pass exactly one of activity_id and product_id",
                "",
            )),
        }
    }

    const fn id(self) -> Uuid {
        match self {
            Self::Activity(id) | Self::Product(id) => id,
        }
    }
}

/// Addons may be managed by activity hosts or by the owning product's group admins.
async fn check_addon_adminship(
    db: impl PgExecutor<'_>,
    user_id: &str,
    owner: AddonOwner,
) -> MinilithResult<()> {
    match owner {
        AddonOwner::Activity(id) => check_activity_adminship(db, user_id, id).await,
        AddonOwner::Product(id) => check_product_adminship(db, user_id, id).await,
    }
}

