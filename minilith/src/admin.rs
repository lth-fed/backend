    /// The physical stock of one product over time, reconstructed from the group's stock
    /// movements. The last point equals the product's current `stock_real`.
    ///
    /// # Errors
    ///
    /// AUTH, DB.
    #[oai(path = "/groups/:group_id/stock-history", method = "get")]
    async fn get_stock_history(
        &self,
        user: User,
        Path(group_id): Path<Uuid>,
        Query(product_id): Query<Uuid>,
    ) -> MinilithResult<Json<Vec<StockPoint>>> {
        check_direct_adminship(&self.db, user.get_id(), group_id).await?;
        let rows = sqlx::query!(
            r#"select
                transaction.time,
                coalesce(sum(case record.kind
                    when 'purchase' then record.amount
                    when 'put-back' then record.amount
                    when 'inventory' then record.amount
                    when 'refund' then -record.amount
                    when 'take-out' then -record.amount
                    else 0
                end), 0)::float8 as "delta!",
                max(case when record.kind = 'balance' then record.amount end)
                    ::float8 as "balance?"
            from stock_transaction_records record
            inner join stock_transactions transaction on transaction.id = record.transaction_id
            where transaction.group_id = $1 and record.product_id = $2
            group by transaction.id, transaction.time
            order by transaction.time, transaction.id"#,
            group_id,
            product_id,
        )
        .fetch_all(&self.db)
        .await?;
        let mut value = 0.0_f64;
        let mut points = Vec::with_capacity(rows.len());
        for row in rows {
            if let Some(balance) = row.balance {
                value = balance;
            }
            value += row.delta;
            #[allow(
                clippy::cast_possible_truncation,
                reason = "stock counts are whole units and bounded by the column type"
            )]
            points.push(StockPoint {
                time: row.time,
                stock_real: value.round() as i32,
            });
        }
        Ok(Json(points))
    }

