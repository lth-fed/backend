fn check_client_id(auth: &ApiAuth, txn_client_id: &str) -> MinilithResult<()> {
    if txn_client_id != auth.client_id {
        return Err(MinilithEndpointError::bad_user_input(
            "client_id doesn't match",
            "",
            "you are not allowed to view or edit this transaction",
            "client_id",
        ));
    }
    Ok(())
}
async fn ensure_id_unused(id: Uuid, txn: &mut Transaction<'_>) -> MinilithResult<()> {
    let exists = sqlx::query_scalar!(
        "select exists (select 1 from transactions where id = $1) as \"exists!\"",
        id
    )
    .fetch_one(&mut txn.executor())
    .await?;
    if exists {
        return Err(MinilithEndpointError::bad_frontend_code(
            "transaction id already used",
            "",
        ));
    }
    Ok(())
}

impl Route {
    #[allow(
        clippy::too_many_lines,
        reason = "the two providers have quite different refund APIs"
    )]
    async fn refund_inner(
        &self,
        auth: ApiAuth,
        id: Uuid,
        amount: Option<i64>,
    ) -> MinilithResult<Json<String>> {
        // The provider is called between two transactions: a connection must never be held over
        // HTTP, so everything we need is read up front and written back after the refund.
        let mut txn = self.db.begin().await?;
        let transaction = sqlx::query!(
            "select client_id, callback_url_v1, payment_reference, refund_reference,
            refund_at, refund_id, provider as \"provider!: Provider\"
            from transactions where id = $1",
            id,
        )
        .fetch_optional(&mut txn.executor())
        .await?
        .wrap_err_not_found()?;

        check_client_id(&auth, &transaction.client_id)?;
        let Some(payment_reference) = &transaction.payment_reference else {
            return Err(MinilithEndpointError::bad_user_input(
                "refund when not paid",
                "",
                "refund is not available until after the purchase is complete",
                "<payment_reference>",
            ));
        };
        if transaction.refund_id.is_some()
            || transaction.refund_reference.is_some()
            || transaction.refund_at.is_some()
        {
            return Err(MinilithEndpointError::bad_user_input(
                "refund when refunded",
                "",
                "refund is not available because it's already happened or is in progress",
                "<refund_reference>",
            ));
        }
        let total: PgMoney = sqlx::query_scalar!(
            "select coalesce(sum(amount), '0.00'::money) as \"amount!\"
            from transaction_wares where transaction_id = $1",
            id
        )
        .fetch_one(&mut txn.executor())
        .await?;
        let swish_number = sqlx::query_scalar!(
            "select swish_number from client_ids where client_id = $1",
            &transaction.client_id
        )
        .fetch_optional(&mut txn.executor())
        .await?
        .wrap_err_internal("client_id not found")?;
        let amount = amount.unwrap_or(total.0);
        if amount <= 0 || amount > total.0 {
            return Err(MinilithEndpointError::bad_user_input(
                "invalid refund amount",
                "",
                "the refund amount must be positive and at most the paid amount",
                "<amount>",
            ));
        }
        txn.commit().await?;

        match transaction.provider {
            Provider::Sumup => {
                let sumup_transaction_id = payment_reference.clone();
                // Claims the refund up front, like the Swish branch: if we crash between the
                // refund and the write below, `runtime::reconcile_refunds` settles it.
                let refund_id = Uuid::new_v4();
                let mut txn = self.db.begin().await?;
                let claimed = sqlx::query!(
                    "update transactions set refund_id = $2
                    where id = $1 and refund_id is null and refund_at is null
                    and refund_reference is null",
                    id,
                    refund_id
                )
                .execute(&mut txn.executor())
                .await?;
                txn.commit().await?;
                if claimed.rows_affected() != 1 {
                    return Err(MinilithEndpointError::bad_user_input(
                        "refund in progress",
                        "",
                        "another refund is already in progress for this transaction",
                        "<refund_reference>",
                    ));
                }

                let refunded = sumup::refund_transaction(
                    self,
                    &transaction.client_id,
                    &sumup_transaction_id,
                    (amount != total.0).then_some(amount),
                )
                .await;
                if let Err(error) = refunded {
                    // A rejection means no refund happened; transport/5xx errors are ambiguous,
                    // so the claim stays and the sweep resolves it.
                    if matches!(error, MinilithEndpointError::Forbidden(_)) {
                        let mut txn = self.db.begin().await?;
                        sqlx::query!(
                            "update transactions set refund_id = null
                            where id = $1 and refund_id = $2",
                            id,
                            refund_id
                        )
                        .execute(&mut txn.executor())
                        .await?;
                        txn.commit().await?;
                    }
                    return Err(error);
                }
                let mut txn = self.db.begin().await?;
                let updated = sqlx::query!(
                    "update transactions
                    set refund_reference = $2, refund_at = now(), refund_id = null
                    where id = $1 and refund_at is null",
                    id,
                    sumup_transaction_id,
                )
                .execute(&mut txn.executor())
                .await?;
                txn.commit().await?;
                if updated.rows_affected() != 1 {
                    return Err(MinilithEndpointError::internal_error(
                        "l1: sumup refunded but the transaction was already marked refunded",
                        (id, sumup_transaction_id, amount, total.0),
                    ));
                }
                callback::send_refunded(
                    self,
                    id,
                    &transaction.callback_url_v1,
                    &transaction.client_id,
                )
                .await;
                Ok(Json(sumup_transaction_id))
            }
            Provider::Swish => {
                let refund_id = Uuid::new_v4();
                let amount = format_money(amount);
                let body = swish::RefundRequest {
                    original_payment_reference: payment_reference.clone(),
                    callback_url: format!("{DOMAIN}/v0/swish-refund-callback"),
                    payer_alias: swish_number,
                    amount,
                    currency: "SEK".to_owned(),
                };

                // Claim the refund before asking Swish: `swish_refund_callback` finds the
                // transaction by `refund_id`, and Swish may post it before we get a response.
                let mut txn = self.db.begin().await?;
                let claimed = sqlx::query!(
                    "update transactions set refund_id = $2
                    where id = $1 and refund_id is null and refund_at is null
                    and refund_reference is null",
                    id,
                    refund_id
                )
                .execute(&mut txn.executor())
                .await?;
                txn.commit().await?;
                if claimed.rows_affected() != 1 {
                    return Err(MinilithEndpointError::bad_user_input(
                        "refund in progress",
                        "",
                        "another refund is already in progress for this transaction",
                        "<refund_reference>",
                    ));
                }

                let client = self.get_swish_client(&transaction.client_id).await?;
                // A transport error leaves the claim in place: Swish may or may not have
                // received the instruction, so only its callback (or a human) can settle it.
                let resp = client
                    .put(swish::refund_instruction_url(refund_id, self.debug.enabled))
                    .json(&body)
                    .send()
                    .await
                    .wrap_err_internal("l1: swish refund transport error")?;
                let status = resp.status();
                if !status.is_success() && status.is_client_error() {
                    let body = resp.text().await.ok();
                    let mut txn = self.db.begin().await?;
                    sqlx::query!(
                        "update transactions set refund_id = null
                        where id = $1 and refund_id = $2",
                        id,
                        refund_id
                    )
                    .execute(&mut txn.executor())
                    .await?;
                    txn.commit().await?;
                    return Err(MinilithEndpointError::internal_error(
                        "l1: swish rejected the refund",
                        (status, body),
                    ));
                }
                drop(client);
                if !status.is_success() {
                    return Err(MinilithEndpointError::internal_error(
                        "l1: swish refund is in an unknown state, keeping the claim",
                        (id, refund_id, status),
                    ));
                }
                Ok(Json(refund_id.to_string()))
            }
            Provider::Stripe | Provider::Free => Err(MinilithEndpointError::bad_user_input(
                "provider not refundable",
                "",
                "this transaction cannot be refunded automatically",
                "<provider>",
            )),
        }
    }
}

