    /// Will return as many infos as ids we received. The order is not guaranteed.
    ///
    /// # Errors
    ///
    /// If any is not associated with your client id, this fails.
    #[oai(path = "/info", method = "post")]
    async fn info(
        &self,
        auth: ApiAuth,
        body: Json<InfoRequest>,
    ) -> MinilithResult<Json<Vec<SingleInfoResponse>>> {
        if body.transaction_ids.is_empty() {
            return Ok(Json(vec![]));
        }
        let transactions = sqlx::query!(
            r#"select payment_reference as "payment_reference?", client_id as "client_id?",
            refund_reference as "refund_reference?", refund_at,
            total_transaction_fee as "total_transaction_fee?",
            customer_id as "customer_id?", provider as "provider?: Provider",
            cancelled_at,
            (select coalesce(sum(amount), '0.00'::money) from transaction_wares
                where transaction_wares.transaction_id = t.id) as "total!",
            --
            t.id as "id!"
            from unnest($1::uuid[]) as t(id)
            left join transactions on transactions.id = t.id"#,
            &body.transaction_ids
        )
        .fetch_all(&self.db)
        .await?;
        for transaction in &transactions {
            if let Some(cid) = &transaction.client_id {
                check_client_id(&auth, cid)?;
            }
        }
        // Only `Swish` charges a fee per refund, and it is a flat per-client amount.
        let client_ids = transactions
            .iter()
            .filter_map(|row| row.client_id.clone())
            .collect::<Vec<_>>();
        let refund_fees = sqlx::query!(
            r#"select client_id, swish_refund_fee as "swish_refund_fee!"
            from client_ids where client_id = any($1)"#,
            &client_ids,
        )
        .fetch_all(&self.db)
        .await?
        .into_iter()
        .map(|row| (row.client_id, row.swish_refund_fee.0))
        .collect::<std::collections::HashMap<_, _>>();
        let mapped = transactions.into_iter().map(|row| SingleInfoResponse {
            id: row.id,
            state: if row.cancelled_at.is_some() {
                TransactionState::Cancelled
            } else if row.refund_at.is_some() || row.refund_reference.is_some() {
                TransactionState::Refunded
            } else if row.payment_reference.is_some() {
                TransactionState::Paid
            } else {
                TransactionState::Pending
            },
            customer_id: row.customer_id,
            purchase_fees: row.total_transaction_fee.map_or(0, |money| money.0),
            total: row.total.0,
            refund_fee: match row.provider {
                Some(Provider::Swish) => row
                    .client_id
                    .as_ref()
                    .and_then(|client_id| refund_fees.get(client_id))
                    .copied()
                    .unwrap_or(0),
                _ => 0,
            },
            provider: row.provider,
            payment_reference: row.payment_reference,
            refund_reference: row.refund_reference,
        });
        Ok(Json(mapped.collect()))
    }
